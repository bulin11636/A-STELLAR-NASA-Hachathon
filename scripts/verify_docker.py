#!/usr/bin/env python3
"""Offline Docker acceptance with isolated state and no model generation.

Builds the real image, checks mounted inputs and readiness, creates a terrain
route/chat, and verifies both after container restart and recreation. Only this run's unique
Compose project and volume are removed. Reports and logs remain under the repo's
ignored processed directory. No user credential file is used.
"""
import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re
import socket
import subprocess
import sys
import time
from uuid import uuid4

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'backend'))


def synthetic_inputs(folder):
    import numpy as np
    import rasterio
    from affine import Affine
    from pyproj import CRS
    dataset = folder/'dataset'; dataset.mkdir(parents=True)
    crs = CRS.from_user_input('+proj=eqc +lat_ts=18.4663 +lon_0=0 +R=3396190 +units=m +no_defs +type=crs').to_wkt().replace('"unknown"','"Mars_Synthetic"')
    with rasterio.open(dataset/'dem.tif','w',driver='GTiff',height=132,width=132,count=1,
        dtype='float32',crs=crs,transform=Affine(20,0,4354000,0,-20,1094000),nodata=-9999) as dst:
        dst.write(np.zeros((132,132),dtype='float32'),1)
    profile = folder/'profile.json'
    profile.write_text(json.dumps(dict(dem='dem.tif',dataset_id='docker-synthetic-plane',roi_id='docker-synthetic-v1',
        window=[1,1,128,128],vertical_units='m',vertical_units_evidence='Synthetic metric plane generated by the Docker acceptance fixture.')))
    return dataset,profile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    inputs = parser.add_mutually_exclusive_group(required=True)
    inputs.add_argument('--synthetic',action='store_true',help='Generate a bounded Mars DEM fixture; usable in CI')
    inputs.add_argument('--dataset-dir',type=Path,help='Read-only real dataset directory')
    parser.add_argument('--profile',type=Path,default=ROOT/'data/samples/a0-planning-profile.example.json')
    parser.add_argument('--output-root',type=Path,default=ROOT/'data/processed/docker-verification')
    parser.add_argument('--no-build',action='store_true',help='Use an existing a-stellar:local image')
    parser.add_argument('--prepare-only',action='store_true',help='Validate/generate inputs without contacting Docker')
    parser.add_argument('--keep',action='store_true',help='Keep this run\'s containers, volume and image for inspection')
    args = parser.parse_args()
    import httpx
    from app.planning.grid import load_grid,digest
    from app.contracts.api import PlanRouteRequest,COORDINATE_SYSTEM
    from run_docker import deployment,parser as launcher_parser
    suffix = uuid4().hex[:12]
    run = args.output_root.resolve()/('run-'+datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')+'-'+suffix)
    run.mkdir(parents=True)
    summary = dict(status='running',run_path=str(run),generation_requests=0,mode='deterministic',project='stellar-smoke-'+suffix)
    command = env = None
    started = False
    image = 'a-stellar:local' if args.no_build else 'a-stellar-smoke:'+suffix
    log = (run/'docker.log').open('w')
    def save(name,body):
        (run/name).write_text(json.dumps(body,allow_nan=False,indent=2)+'\n')
    def docker(argv, *, capture=False, check=True):
        result = subprocess.run(argv,cwd=ROOT,env=env,text=True,stdout=subprocess.PIPE if capture else log,
            stderr=log,check=False)
        if check and result.returncode:
            raise RuntimeError('A Docker command failed; inspect docker.log.')
        return result.stdout.strip() if capture else result.returncode
    def stage(name):
        summary['stage']=name; print(name,flush=True)
    def wait_ready(client):
        deadline = time.monotonic()+90
        while time.monotonic()<deadline:
            try:
                response=client.get('/api/v1/ready',timeout=3)
                if response.status_code==200:
                    assert response.json()['a0_mode']=='deterministic'
                    return
            except httpx.HTTPError:
                pass
            time.sleep(.5)
        raise RuntimeError('The container did not become ready; inspect docker.log.')
    def wait_healthy(container):
        deadline=time.monotonic()+90
        while time.monotonic()<deadline:
            status=json.loads(docker(['docker','inspect',container],capture=True))[0]['State'].get('Health',{}).get('Status')
            if status=='healthy': return
            if status=='unhealthy': raise RuntimeError('The image health check failed; inspect docker.log.')
            time.sleep(1)
        raise RuntimeError('The image health check never became healthy.')
    try:
        stage('prepare_inputs')
        datasets,profile = synthetic_inputs(run) if args.synthetic else (args.dataset_dir.expanduser().resolve(),args.profile.expanduser().resolve())
        grid=load_grid(profile,dataset_root=datasets)
        if grid.metadata.height<=100 or grid.metadata.width<=100 or not grid.allowed[20,20] or not grid.allowed[100,100]:
            raise RuntimeError('Acceptance requires traversable demo cells (20,20) and (100,100) in a grid larger than 100 cells per axis.')
        request=PlanRouteRequest(region_id='jezero',coordinate_system=COORDINATE_SYSTEM,
            start=grid.wire(*grid.center((20,20))),goal=grid.wire(*grid.center((100,100))),mode='shortest').model_dump(mode='json')
        summary['planning_extent']='native_demo'
        if not args.synthetic:
            from app.planning.service import PlanningService
            planning=PlanningService('computed',profile,run/'preflight-routes',dataset_root=datasets)
            regional=planning.regional_example()
            if regional is not None:
                request=regional.model_dump(mode='json')
                summary['planning_extent']='regional_example'
        source_hash=digest(grid.source_path)
        runtime=run/'runtime.env'; runtime.write_text(''); runtime.chmod(0o600)
        with socket.socket() as probe:
            probe.bind(('127.0.0.1',0)); port=probe.getsockname()[1]
        launch=launcher_parser().parse_args(['--env-file',str(runtime),'--dataset-dir',str(datasets),
            '--planning-profile',str(profile),'--mode','deterministic','--port',str(port),'--project-name',summary['project']])
        command,env=deployment(launch)
        env['A_STELLAR_IMAGE']=image
        summary.update(port=port,source_sha256=source_hash,synthetic=args.synthetic)
        save('request.json',request)
        if args.prepare_only:
            summary['status']='prepared'
        else:
            stage('check_engine')
            docker(['docker','version','--format','{{.Server.Version}}'])
            docker(['docker','compose','version'])
            stage('build_and_start')
            started=True
            docker(command+['up','-d']+(['--no-build'] if args.no_build else ['--build']))
            with httpx.Client(base_url=f'http://127.0.0.1:{port}',timeout=90,trust_env=False) as client:
                wait_ready(client)
                stage('verify_mounts_and_configuration')
                container=docker(command+['ps','-q','app'],capture=True)
                inspection=json.loads(docker(['docker','inspect',container],capture=True))[0]
                mounts={m['Destination']:m for m in inspection['Mounts']}
                for path in ['/datasets','/run/a-stellar/runtime.env','/run/a-stellar/planning.json']:
                    assert mounts[path]['RW'] is False,path
                assert mounts['/var/lib/a-stellar']['RW'] is True
                wait_healthy(container)
                docker(command+['exec','-T','app','python','-c',
                    "import os; from pathlib import Path; assert os.geteuid()!=0; assert not Path('/app/.env').exists(); assert not Path('/app/backend/.env').exists()"])
                ui=client.get('/')
                assert ui.status_code==200
                assets=re.findall(r'(?:src|href)="(/assets/[^"]+)"',ui.text)
                assert assets
                for asset in assets: assert client.get(asset).status_code==200,asset
                assert client.get('/api/v1/health').status_code==200
                assert client.get('/api/v1/a0/status').json()['configured'] is False
                missing_profile="from fastapi.testclient import TestClient; from app.main import app; c=TestClient(app); assert c.get('/api/v1/ready').status_code==503; assert c.get('/api/v1/health').status_code==200"
                docker(command+['run','--rm','--no-deps','-e','A_STELLAR_PLANNING_PROFILE=/run/a-stellar/missing.json','app','python','-c',missing_profile])
                missing_env="from app.coordinator.settings import environment\ntry:\n environment()\nexcept ValueError:\n pass\nelse:\n raise AssertionError('Missing explicit runtime file must fail')"
                docker(command+['run','--rm','--no-deps','-e','A_STELLAR_ENV_FILE=/run/a-stellar/missing.env','app','python','-c',missing_env])
                stage('plan_chat_and_failed_request')
                key='docker-plan-'+suffix
                headers={'Idempotency-Key':key}
                response=client.post('/api/v1/routes/plan',json=request,headers=headers)
                assert response.status_code==200,response.text
                result=response.json(); route_id=result['route_id']
                assert result['source']=='computed' and result['metrics']['distance_m']>0
                stored=client.get('/api/v1/routes/'+route_id).json()
                assert stored['metadata']['validation']['status']=='passed'
                assert stored['metadata']['sources'][0]['sha256']==source_hash
                summary.update(distance_m=result['metrics']['distance_m'],
                    planning_resolution_m=stored['metadata']['grid']['planning_resolution_m'])
                save('stored-route.json',stored)
                body=dict(message='Explain the terrain-only limits.',request_id='docker-chat-'+suffix,
                    advanced_context=dict(schema_version='1',interface_mode='advanced',route_objective=request['mode'],
                        required_waypoints=request.get('waypoints',[]),analysis_focus=['terrain'],allow_supported_revision=False))
                chat_url='/api/v1/routes/'+route_id+'/chat'
                chat=client.post(chat_url,json=body)
                assert chat.status_code==200,chat.text
                assert chat.json()['result'] is None and chat.json()['metadata'] is None
                assert client.post(chat_url,json=body).json()==chat.json()
                bad_key='docker-bad-'+suffix
                invalid={**request,'start':{'longitude':0.0,'latitude':0.0}}
                failed=client.post('/api/v1/routes/plan',json=invalid,headers={'Idempotency-Key':bad_key})
                assert failed.status_code==400,failed.text
                assert client.get('/api/v1/routes/requests/'+bad_key).json()['state']=='failed'
                stage('restart_and_replay')
                original_started=inspection['State']['StartedAt']
                docker(command+['restart','app'])
                wait_ready(client)
                inspection=json.loads(docker(['docker','inspect',container],capture=True))[0]
                assert inspection['State']['StartedAt']!=original_started
                def verify_persistence():
                    assert client.get('/api/v1/routes/'+route_id).json()==stored
                    assert len(client.get(chat_url).json()['messages'])==1
                    assert client.post(chat_url,json=body).json()==chat.json()
                    assert client.post('/api/v1/routes/plan',json=request,headers=headers).json()==result
                    assert client.get('/api/v1/routes/requests/'+key).json()['state']=='succeeded'
                    assert client.post('/api/v1/routes/plan',json=invalid,headers={'Idempotency-Key':bad_key}).json()==failed.json()
                verify_persistence()
                stage('recreate_and_replay')
                docker(command+['up','-d','--no-build','--force-recreate','app'])
                wait_ready(client)
                recreated=docker(command+['ps','-q','app'],capture=True)
                assert recreated!=container
                verify_persistence()
                assert digest(grid.source_path)==source_hash
                summary.update(status='passed',route_id=route_id,checks=['production_ui_assets_api','image_health_check','non_root_runtime','read_only_source_and_private_file_mounts',
                    'missing_profile_readiness','missing_explicit_env_rejected','terrain_plan_and_chat','failed_request_persistence',
                    'restart_route_history_and_idempotent_replay','recreation_with_persistent_named_state','source_bytes_unchanged'])
    except (Exception,KeyboardInterrupt) as error:
        summary.update(status='blocked' if summary.get('stage')=='check_engine' else 'failed',error_type=type(error).__name__,
            message='Docker engine/Compose is unavailable; enable the Docker Desktop WSL 2 integration.' if summary.get('stage')=='check_engine' else
            str(error) if isinstance(error,(AssertionError,RuntimeError)) else 'Inspect docker.log and the local prerequisites.')
        if started:
            docker(command+['logs','--no-color','app'],check=False)
    finally:
        if started and not args.keep:
            cleaned=docker(command+['down','--volumes','--remove-orphans'],check=False)==0
            if cleaned and not args.no_build:
                docker(['docker','image','rm',image],check=False)
            summary['resources_removed']=cleaned
        log.close()
        save('summary.json',summary)
        print(json.dumps(summary,indent=2))
    return 0 if summary['status'] in ('passed','prepared') else 1


if __name__=='__main__':
    raise SystemExit(main())
