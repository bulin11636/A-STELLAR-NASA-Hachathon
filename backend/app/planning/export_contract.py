"""Generate the browser's nested metadata types and runtime schema from Pydantic."""
import json
from pathlib import Path
from app.contracts.routes import StoredRouteResponse
from app.contracts.chat import ChatResponse


def export(root):
    schema=StoredRouteResponse.model_json_schema(mode='serialization')
    def ts(s):
        if '$ref' in s: return s['$ref'].split('/')[-1]
        if 'const' in s: return json.dumps(s['const'])
        if 'enum' in s: return ' | '.join(json.dumps(v) for v in s['enum'])
        if 'anyOf' in s: return ' | '.join(ts(x) for x in s['anyOf'])
        kind=s.get('type')
        if kind in ('number','integer'): return 'number'
        if kind=='null': return 'null'
        if kind=='boolean': return 'boolean'
        if kind=='string': return 'string'
        if kind=='array':
            if 'prefixItems' in s: return '['+', '.join(ts(x) for x in s['prefixItems'])+']'
            return 'Array<'+ts(s['items'])+'>'
        if kind=='object':
            if 'properties' in s:
                return '{\n'+'\n'.join('  '+k+': '+ts(v)+';' for k,v in s['properties'].items())+'\n}'
            return 'Record<string, '+ts(s.get('additionalProperties',{}))+'>'
        return 'unknown'
    chat_schema=ChatResponse.model_json_schema(mode='serialization')
    definitions={**schema['$defs'],**chat_schema['$defs']}
    out=['// Generated by python -m app.planning.export_contract; do not hand edit.']
    for name,definition in [*definitions.items(),('StoredRouteResponse',schema),('ChatResponse',chat_schema)]:
        out.append('export type '+name+' = '+ts(definition)+';')
    root.mkdir(parents=True,exist_ok=True)
    (root/'routeMetadata.ts').write_text('\n\n'.join(out)+'\n')
    (root/'storedRoute.schema.json').write_text(json.dumps(schema,indent=2)+'\n')
    (root/'chat.schema.json').write_text(json.dumps(chat_schema,indent=2)+'\n')


if __name__=='__main__':
    export(Path(__file__).resolve().parents[3]/'frontend/src/types')
